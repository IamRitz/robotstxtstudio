import { describe, expect, it } from "vitest";
import { analyzePolicySet } from "./impact";
import {
  blockAllAiCrawlers,
  emptyPolicySet,
  fromWebsitePreset,
  setPermission,
} from "./permissions";
import type { PolicyImpact } from "./types";

const crawler = (impact: PolicyImpact, id: string) => impact.crawlers.find((c) => c.crawler.id === id)!;
const recIds = (impact: PolicyImpact) => impact.recommendations.map((r) => r.crawlerId);

describe("analyzePolicySet — no direct robots.txt", () => {
  it("renders text through the Generator", () => {
    const impact = analyzePolicySet(emptyPolicySet());
    expect(impact.text).toContain("generated by Robots.txt Studio");
    expect(impact.validation.isValid).toBe(true);
    expect(impact.explanation.aiCrawlers).toHaveLength(5);
  });
});

describe("analyzePolicySet — permission scenarios", () => {
  it("explicit block: the crawler is blocked from the whole site", () => {
    const impact = analyzePolicySet(setPermission(emptyPolicySet(), "gptbot", "block"));
    const gpt = crawler(impact, "gptbot");
    expect(gpt).toMatchObject({ state: "block", access: "blocked" });
    expect(gpt.summary).toContain("blocked from accessing your entire site");
    expect(impact.text).toContain("User-agent: GPTBot");
  });

  it("explicit allow: the crawler can access the site", () => {
    const impact = analyzePolicySet(setPermission(emptyPolicySet(), "googlebot", "allow"));
    const google = crawler(impact, "googlebot");
    expect(google).toMatchObject({ state: "allow", access: "allowed" });
    expect(google.summary).toContain("allowed");
  });

  it("inheritance: undecided crawlers inherit the default and are recommended a policy", () => {
    const impact = analyzePolicySet(emptyPolicySet());
    const gpt = crawler(impact, "gptbot");
    expect(gpt).toMatchObject({ state: "inherit", access: "allowed" });
    expect(gpt.summary).toContain("inherit");
    expect(recIds(impact)).toContain("gptbot");
  });

  it("mixed: block, allow, and inherit coexist with correct recommendations", () => {
    let set = emptyPolicySet();
    set = setPermission(set, "gptbot", "block");
    set = setPermission(set, "perplexitybot", "allow");
    set = setPermission(set, "claudebot", "inherit");
    const impact = analyzePolicySet(set);
    expect(crawler(impact, "gptbot").access).toBe("blocked");
    expect(crawler(impact, "perplexitybot").access).toBe("allowed");
    expect(crawler(impact, "claudebot").state).toBe("inherit");
    const ids = recIds(impact);
    expect(ids).toContain("claudebot"); // undecided AI → recommend
    expect(ids).not.toContain("gptbot"); // decided
    expect(ids).not.toContain("perplexitybot"); // decided
  });
});

describe("analyzePolicySet — AI scenarios", () => {
  it("Block all AI crawlers blocks training and search categories", () => {
    const impact = analyzePolicySet(blockAllAiCrawlers(emptyPolicySet()));
    for (const id of ["gptbot", "claudebot", "ccbot", "perplexitybot", "google-extended"]) {
      expect(crawler(impact, id).access).toBe("blocked");
    }
    const training = impact.categories.find((c) => c.category === "ai-training")!;
    expect(training.blocked).toBe(training.total);
  });

  it("a website preset summarizes categories", () => {
    const impact = analyzePolicySet(fromWebsitePreset("blog"));
    const training = impact.categories.find((c) => c.category === "ai-training")!;
    expect(training.blocked).toBe(5);
    const search = impact.categories.find((c) => c.category === "search-engine")!;
    expect(search.allowed).toBe(3);
  });
});
