/**
 * Build a canonical {@link RobotsFile} from a {@link GeneratorConfig}.
 *
 * The `LineWriter` is the single canonical robots.txt formatter: it emits raw lines
 * (the lossless `directives` backbone) while building the structured `groups`/
 * `sitemaps` in the same pass, so the AST and its text never diverge. Only *blocked*
 * crawlers get explicit `Disallow: /` groups; allowed crawlers inherit the
 * `User-agent: *` baseline (giving them their own `Allow: /` group would bypass the
 * global path disallows).
 */
import { analyzePath } from "@/parser";
import { ALL_CRAWLERS, CATEGORY_LABELS, CATEGORY_ORDER } from "@/config/crawlers";
import type {
  Crawler,
  CrawlerCategory,
  CrawlRule,
  CrawlRuleType,
  Directive,
  GeneratorConfig,
  RobotsFile,
  RobotsGroup,
  Sitemap,
} from "@/types";
import { TEMPLATE_LABELS } from "./presets";

/** Emits robots.txt lines and tracks the directive backbone + line numbers. */
class LineWriter {
  private readonly directives: Directive[] = [];
  private line = 0;

  private emit(field: Directive["field"], value: string, raw: string): number {
    this.line += 1;
    this.directives.push({ field, value, raw, line: this.line });
    return this.line;
  }

  comment(text: string): number {
    return this.emit("comment", text, `# ${text}`);
  }
  blank(): number {
    return this.emit("blank", "", "");
  }
  userAgent(token: string): number {
    return this.emit("user-agent", token, `User-agent: ${token}`);
  }
  rule(type: CrawlRuleType, path: string): CrawlRule {
    const raw = `${type === "allow" ? "Allow" : "Disallow"}: ${path}`;
    const line = this.emit(type, path, raw);
    const { hasWildcard, hasEndAnchor } = analyzePath(path);
    return { type, path, hasWildcard, hasEndAnchor, raw, line };
  }
  crawlDelay(seconds: number): number {
    return this.emit("crawl-delay", String(seconds), `Crawl-delay: ${seconds}`);
  }
  sitemap(url: string): Sitemap {
    return { url, line: this.emit("sitemap", url, `Sitemap: ${url}`) };
  }

  finish(): { directives: Directive[]; lineCount: number; text: string } {
    return {
      directives: this.directives,
      lineCount: this.directives.length,
      text: this.directives.map((d) => d.raw).join("\n"),
    };
  }
}

/** Blocked crawlers grouped by category, preserving catalog order. */
function blockedByCategory(config: GeneratorConfig): Map<CrawlerCategory, Crawler[]> {
  const map = new Map<CrawlerCategory, Crawler[]>();
  for (const crawler of ALL_CRAWLERS) {
    if (config.crawlerPolicies[crawler.id] === "block") {
      const list = map.get(crawler.category) ?? [];
      list.push(crawler);
      map.set(crawler.category, list);
    }
  }
  return map;
}

/** Build the canonical RobotsFile AST for a config. */
export function buildRobotsFile(config: GeneratorConfig): RobotsFile {
  const writer = new LineWriter();
  const groups: RobotsGroup[] = [];
  const sitemaps: Sitemap[] = [];

  writer.comment("robots.txt generated by Robots.txt Studio");
  if (config.template) writer.comment(`Template: ${TEMPLATE_LABELS[config.template]}`);

  // One group per category of blocked crawlers.
  const blocked = blockedByCategory(config);
  for (const category of CATEGORY_ORDER) {
    const crawlers = blocked.get(category);
    if (!crawlers || crawlers.length === 0) continue;
    writer.blank();
    writer.comment(`${CATEGORY_LABELS[category]} (blocked)`);
    const userAgentLines = crawlers.map((c) => writer.userAgent(c.userAgent));
    const rule = writer.rule("disallow", "/");
    groups.push({
      userAgents: crawlers.map((c) => c.userAgent),
      rules: [rule],
      lineRange: { start: userAgentLines[0] ?? rule.line, end: rule.line },
    });
  }

  // Baseline group for everyone else.
  writer.blank();
  writer.comment("All other crawlers");
  const wildcardStart = writer.userAgent("*");
  const rules: CrawlRule[] = [writer.rule("allow", "/")];
  for (const path of config.disallowPaths) rules.push(writer.rule("disallow", path));
  let crawlDelay: number | undefined;
  let endLine = rules[rules.length - 1]?.line ?? wildcardStart;
  if (config.crawlDelay !== undefined) {
    endLine = writer.crawlDelay(config.crawlDelay);
    crawlDelay = config.crawlDelay;
  }
  groups.push({
    userAgents: ["*"],
    rules,
    ...(crawlDelay !== undefined ? { crawlDelay } : {}),
    lineRange: { start: wildcardStart, end: endLine },
  });

  if (config.sitemapUrl) {
    writer.blank();
    sitemaps.push(writer.sitemap(config.sitemapUrl));
  }

  const { directives, lineCount, text } = writer.finish();
  return { directives, groups, sitemaps, unknownDirectives: [], lineCount, source: text };
}
